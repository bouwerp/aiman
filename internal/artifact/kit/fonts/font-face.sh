#!/usr/bin/env bash
# Prints the @font-face block theme.css carries between its "fonts:begin" and
# "fonts:end" markers. A sandboxed artifact page has origin null and Chromium
# fetches fonts in CORS mode, so same-host font files are blocked; the faces
# are inlined as data: URIs instead (font-src allows data:).
#   font-face.sh          print the block
#   font-face.sh --check  exit 1 unless theme.css holds exactly this block
set -euo pipefail
cd "$(dirname "$0")"
block() {
  echo "/* fonts:begin (generated by fonts/font-face.sh; OFL 1.1, see fonts/OFL.txt and fonts/SOURCES.md) */"
  local spec fam slug w
  for spec in "IBM Plex Sans:ibm-plex-sans:400 500 600" "IBM Plex Mono:ibm-plex-mono:400 500" \
              "Inter:inter:400 500 600" "Space Grotesk:space-grotesk:500 600 700" "JetBrains Mono:jetbrains-mono:400 500"; do
    IFS=: read -r fam slug ws <<<"$spec"
    for w in $ws; do
      printf '@font-face { font-family:"%s"; font-style:normal; font-weight:%s; font-display:swap; src:url("data:font/woff2;base64,%s") format("woff2"); }\n' \
        "$fam" "$w" "$(base64 -w0 "$slug-latin-$w-normal.woff2")"
    done
  done
  echo "/* fonts:end */"
}
if [ "${1:-}" = "--check" ]; then
  diff <(block) <(sed -n '/fonts:begin/,/fonts:end/p' ../theme.css) >/dev/null || { echo "theme.css font block is stale: run $0 and paste its output" >&2; exit 1; }
  echo "theme.css font block matches fonts/*.woff2"
else
  block
fi

//go:build !windows

package awsdelegation

import (
	"errors"
	"os"
	"path/filepath"
	"syscall"
)

// lockHostCredentials takes an exclusive flock on path, creating it 0600, and returns
// its release. It blocks until the holder lets go; holders only merge and rename.
func lockHostCredentials(path string) (func(), error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	for {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX)
		if !errors.Is(err, syscall.EINTR) {
			break
		}
	}
	if err != nil {
		_ = f.Close()
		return nil, err
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
	}, nil
}
